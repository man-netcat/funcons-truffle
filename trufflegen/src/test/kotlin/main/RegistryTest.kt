package main

import cbs.CBSParser.FunconDefinitionContext
import cbs.CBSParser.TypeDefinitionContext
import main.objects.TypeObject
import objects.FunconObject
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Assertions.assertSame
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * Names resolve to objects, whichever file declared them.
 *
 * The registry replaced a mutable map that was global, so the interesting part is
 * not that a name resolves but that an object registered under an alias and a
 * name that is already registered cannot be silently lost.
 */
class RegistryTest {
    private fun funcon(registry: RegistryBuilder, source: String): FunconObject =
        FunconObject(node<FunconDefinitionContext>(source), metaVariables = emptySet(), registry = registry)

    private fun type(registry: RegistryBuilder, source: String): TypeObject =
        TypeObject(node<TypeDefinitionContext>(source), emptySet(), registry)

    @Test
    fun aliasLookupTest() {
        val registry = RegistryBuilder(emptySet())
        val funcon = funcon(registry, "Funcon f : value-types Alias g = f")
        registry.add(funcon)

        assertSame(funcon, registry["f"])
        assertSame(funcon, registry["g"])
        // One object under two names is still one object: the alias file is
        // generated by walking the registry, so counting it twice would emit
        // every alias twice.
        assertEquals(1, registry.objects.size)
    }

    @Test
    fun undeclaredTest() {
        val registry = RegistryBuilder(emptySet())
        assertNull(registry["f"])
    }

    @Test
    fun builtinTest() {
        val registry = RegistryBuilder(setOf("print"))
        val built = funcon(registry, "Funcon print : =>empty-type")
        val generated = funcon(registry, "Funcon list-append(X:list(T), Y:T) : list(T)")
        registry.add(built)
        registry.add(generated)

        assertTrue(built.builtin)
        assertTrue(!generated.builtin)
    }

    @Test
    fun subtypeIndexTest() {
        val registry = RegistryBuilder(emptySet())
        val lists = type(registry, "Type lists(T) ~> value-types")
        // `strings` is declared a subtype of `lists(characters)`, as Strings.cbs
        // writes it. The index is keyed on the supertype name as written, so a
        // `lists(T)` and a `lists(characters)` would both land under "lists".
        val strings = type(registry, "Type strings ~> lists(characters)")
        val integers = type(registry, "Type integers ~> value-types")
        listOf(lists, strings, integers).forEach { registry.add(it) }

        assertEquals(listOf(strings), registry.subtypesOf("lists"))
        assertEquals(listOf(lists, integers), registry.subtypesOf("value-types"))
        assertEquals(emptyList<TypeObject>(), registry.subtypesOf("characters"))
    }
}
